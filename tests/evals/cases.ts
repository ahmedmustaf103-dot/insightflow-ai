import type { AnalysisPlan } from "@/lib/analysis/types";
import { plan } from "../helpers";

const year = (value: string) =>
  ({ column: "order_date", op: "between" as const, value: [`${value}-01-01`, `${value}-12-31`] });

const revenue2025 = plan({
  operation: "aggregate",
  filters: [year("2025")],
  groupBy: ["product"],
  metrics: [{ column: "revenue", agg: "sum" }],
  sortBy: "sum_revenue",
  sortDirection: "desc",
  rationale: "Sum revenue by product for 2025.",
});

